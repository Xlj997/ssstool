"""打开/关闭带 CDP 端口的 Chrome。

关键设计（依据实测，见 docs/capabilities/browser.md）：
- 一律用独立 ``--user-data-dir`` 启动，因为 Chrome 136+ 在默认用户配置下忽略
  ``--remote-debugging-port``，且浏览器已在运行时新进程会立刻退出（handoff），拿不到端口。
- PID 以「端口归属进程」为准，不信 Popen 返回的 pid（handoff 场景下它会立刻退出）。
- 关闭前必须校验「端口归属 + 进程名 = chrome.exe」，绝不按 PID 盲杀。
"""

from __future__ import annotations

import json
import os
import secrets
import shutil
import subprocess
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

from ssstool import _state, _win
from ssstool.errors import EXIT_CDP_UNAVAILABLE, EXIT_FAILURE, EXIT_USAGE, SsstoolError

DEFAULT_PORT = 9222
DEFAULT_TIMEOUT = 30.0
CLOSE_TIMEOUT = 20.0
PROFILE_ROOT_NAME = ".ssstool"
_CDP_VERSION_PATH = "/json/version"
_GITIGNORE_CONTENT = "# generated by ssstool: keep browser profiles out of version control\n*\n"


@dataclass
class Session:
    run_id: str
    pid: int
    port: int
    profile: str
    profile_dir: str | None
    project_dir: str | None
    chrome: str
    cdp_url: str
    ws_url: str | None
    browser_version: str | None
    started_at: str
    user_data_dir: str | None = None
    user_data_dir_source: str | None = None
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, object]:
        return {
            "run_id": self.run_id,
            "pid": self.pid,
            "port": self.port,
            "profile": self.profile,
            "profile_dir": self.profile_dir,
            "project_dir": self.project_dir,
            "chrome": self.chrome,
            "cdp_url": self.cdp_url,
            "ws_url": self.ws_url,
            "browser_version": self.browser_version,
            "started_at": self.started_at,
            "user_data_dir": self.user_data_dir,
            "user_data_dir_source": self.user_data_dir_source,
        }


@dataclass
class CloseResult:
    port: int
    pid: int
    already_stopped: bool
    profile_dir: str | None
    profile_removed: bool
    warnings: list[str] = field(default_factory=list)

    def to_dict(self) -> dict[str, object]:
        return {
            "port": self.port,
            "pid": self.pid,
            "already_stopped": self.already_stopped,
            "profile_dir": self.profile_dir,
            "profile_removed": self.profile_removed,
            "warnings": list(self.warnings),
        }


def _new_run_id(port: int) -> str:
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    return f"{stamp}-{port}-{os.getpid()}-{secrets.token_hex(3)}"


def _ensure_self_ignoring(directory: Path) -> None:
    """在 .ssstool 下放一个内容为 ``*`` 的 .gitignore，避免污染调用方仓库。

    不修改调用方根 .gitignore：那是用户资产，工具无权悄悄改。
    """
    gitignore = directory / ".gitignore"
    if gitignore.exists():
        return
    try:
        directory.mkdir(parents=True, exist_ok=True)
        gitignore.write_text(_GITIGNORE_CONTENT, encoding="utf-8")
    except OSError:
        return


def _prepare_profile(
    profile: str, project_dir: str | None, run_id: str
) -> tuple[Path | None, list[str]]:
    warnings: list[str] = []
    if profile == "default":
        return None, warnings

    if project_dir:
        root = Path(project_dir).expanduser()
        if not root.is_dir():
            raise SsstoolError(f"--project-dir does not exist: {root}", code=EXIT_USAGE)
        root = root.resolve()
    else:
        root = Path.cwd()

    target = root / PROFILE_ROOT_NAME / "browser" / run_id / "profile"
    try:
        target.mkdir(parents=True, exist_ok=True)
        _ensure_self_ignoring(root / PROFILE_ROOT_NAME)
        return target, warnings
    except OSError as exc:
        fallback_base = Path(os.environ.get("LOCALAPPDATA") or Path.home())
        fallback = fallback_base / "ssstool" / "browser" / run_id / "profile"
        fallback.mkdir(parents=True, exist_ok=True)
        warnings.append(f"project dir not writable ({exc}); profile moved to {fallback}")
        return fallback, warnings


def _launch(chrome: Path, port: int, user_data_dir: Path | None) -> subprocess.Popen[bytes]:
    args = [str(chrome)]
    if user_data_dir is not None:
        args.append(f"--user-data-dir={user_data_dir}")
    args.extend(
        [
            f"--remote-debugging-port={port}",
            "--remote-debugging-address=127.0.0.1",
            "--no-first-run",
            "--no-default-browser-check",
            "about:blank",
        ]
    )
    creationflags = _win.DETACHED_PROCESS | _win.CREATE_NO_WINDOW | _win.CREATE_NEW_PROCESS_GROUP
    return subprocess.Popen(
        args,
        stdin=subprocess.DEVNULL,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
        close_fds=True,
        creationflags=creationflags,
    )


def _read_cdp_version(port: int) -> dict[str, object]:
    url = f"http://127.0.0.1:{port}{_CDP_VERSION_PATH}"
    with urllib.request.urlopen(url, timeout=1.5) as response:
        payload = json.loads(response.read().decode("utf-8"))
    if not isinstance(payload, dict) or "webSocketDebuggerUrl" not in payload:
        raise ValueError("unexpected /json/version payload")
    return payload


def _wait_for_cdp(
    port: int, timeout: float, proc: subprocess.Popen[bytes], profile: str
) -> dict[str, object]:
    deadline = time.monotonic() + timeout
    exited_at: float | None = None
    last_error: Exception | None = None
    while time.monotonic() < deadline:
        try:
            return _read_cdp_version(port)
        except (urllib.error.URLError, OSError, ValueError) as exc:
            last_error = exc
        if proc.poll() is not None:
            # 默认配置 + 已有 Chrome 时新进程会 handoff 后立刻退出；最多再给 1.5s
            exited_at = exited_at or time.monotonic()
            if time.monotonic() - exited_at > 1.5:
                break
        time.sleep(0.25)

    if profile == "default":
        hint = (
            "Chrome 136+ ignores --remote-debugging-port on the default profile even after all "
            "Chrome processes are terminated; use --profile temp for a reliable CDP endpoint."
        )
    else:
        hint = (
            "Chrome exited before exposing the CDP endpoint. Check that the port is free, that no "
            "other Chrome instance locks the profile directory, and retry with a larger --timeout."
        )
    detail = f" Last error: {last_error}" if last_error else ""
    raise SsstoolError(
        f"CDP endpoint did not become ready on port {port}. {hint}{detail}",
        code=EXIT_CDP_UNAVAILABLE,
    )


def _abort_launch(proc: subprocess.Popen[bytes], profile_dir: Path | None) -> None:
    """失败回滚：只杀我们自己启动的 chrome 进程，临时 profile 一并删除。"""
    if proc.poll() is None:
        try:
            if (_win.process_name(proc.pid) or "").lower() == "chrome.exe":
                _win.kill_tree(proc.pid)
        except SsstoolError:
            pass
    if profile_dir is not None:
        _kill_profile_processes(profile_dir)
        _remove_tree(profile_dir)


def _kill_profile_processes(profile_dir: Path) -> list[int]:
    """兜底清理命令行仍引用该 profile 的 chrome 进程。

    进程树终止可能漏掉被重新挂载的 renderer（实测 close 后仍残留一个 renderer 持有
    已删除的 profile 路径）。按 profile 绝对路径匹配是唯一可靠的归属证据。
    """
    marker = str(profile_dir).lower()
    killed: list[int] = []
    for item in _win.chrome_processes():
        command = str(item.get("CommandLine") or "").lower()
        if marker not in command:
            continue
        try:
            child_pid = int(item.get("ProcessId") or 0)
        except (TypeError, ValueError):
            continue
        if child_pid <= 0:
            continue
        try:
            _win.kill_tree(child_pid)
            killed.append(child_pid)
        except SsstoolError:
            continue
    return killed


def _remove_tree(path: Path) -> bool:
    for _ in range(10):
        try:
            shutil.rmtree(path)
            return True
        except FileNotFoundError:
            return True
        except OSError:
            time.sleep(0.25)
    return False


def _prune_empty_parents(path: Path, levels: int = 2) -> None:
    """删掉空的 run 目录与 browser 目录，但绝不越过 .ssstool 根。"""
    current = path
    for _ in range(levels):
        try:
            current.rmdir()
        except OSError:
            break
        current = current.parent


def _owns_profile_dir(path: Path) -> bool:
    """只允许删除 ssstool 自己创建的 profile 目录，防止被篡改的状态文件指向任意路径。"""
    if path.name != "profile":
        return False
    return any(parent.name == "browser" for parent in path.parents)


def _session_alive(data: dict[str, object]) -> bool:
    try:
        pid = int(data.get("pid") or 0)
        port = int(data.get("port") or 0)
        if not _win.pid_alive(pid):
            return False
        return _win.port_owner(port) == pid
    except (SsstoolError, ValueError, OSError):
        return False


def prune_stale_sessions() -> list[str]:
    """清理已死会话的临时 profile 与状态文件；返回被清理的 run_id。"""
    removed: list[str] = []
    for state_path, data in _state.read_sessions():
        if _session_alive(data):
            continue
        profile_dir = data.get("profile_dir")
        if data.get("temp_profile") and profile_dir:
            candidate = Path(str(profile_dir))
            if _owns_profile_dir(candidate):
                _remove_tree(candidate)
                _prune_empty_parents(candidate.parent)
        _state.delete_session(state_path)
        removed.append(str(data.get("run_id", state_path.stem)))
    return removed


def open_browser(
    *,
    port: int = DEFAULT_PORT,
    profile: str = "temp",
    project_dir: str | None = None,
    chrome_path: str | None = None,
    timeout: float = DEFAULT_TIMEOUT,
    force: bool = False,
) -> Session:
    _win.ensure_windows()
    if profile not in {"temp", "default"}:
        raise SsstoolError(f"unknown profile mode: {profile}", code=EXIT_USAGE)
    if not 1 <= port <= 65535:
        raise SsstoolError("port must be 1..65535", code=EXIT_USAGE)
    if timeout <= 0:
        raise SsstoolError("timeout must be positive", code=EXIT_USAGE)
    if profile == "default" and not force:
        raise SsstoolError(
            "--profile default terminates ALL running Chrome windows; add --force to confirm.",
            code=EXIT_USAGE,
        )

    warnings = prune_stale_sessions()
    if _win.port_in_use(port):
        raise SsstoolError(
            f"port {port} is already in use. Pick another port with --port, or if it is a stale "
            f"ssstool browser run: ssstool browser close --port {port}",
            code=EXIT_FAILURE,
        )

    chrome = _win.find_chrome(chrome_path)
    user_data_dir: Path | None = None
    user_data_dir_source: str | None = None
    if profile == "default":
        # 真实配置不一定在 Default 目录：策略 → 运行态命令行 → 快捷方式 → 标准路径。
        user_data_dir, user_data_dir_source = _win.resolve_chrome_user_data_dir()
        killed = _win.kill_all_chrome()
        warnings.append(
            f"terminated {killed} Chrome process(es) before restarting with the default profile"
        )
        warnings.append(f"user data dir: {user_data_dir} (source: {user_data_dir_source})")
    run_id = _new_run_id(port)
    profile_dir, profile_warnings = _prepare_profile(profile, project_dir, run_id)
    warnings.extend(profile_warnings)
    launch_dir = profile_dir if profile == "temp" else user_data_dir

    proc = _launch(chrome, port, launch_dir)
    probe_timeout = min(timeout, 10.0) if profile == "default" else timeout
    try:
        version = _wait_for_cdp(port, probe_timeout, proc, profile)
    except SsstoolError as exc:
        if profile == "default":
            standard = _win.standard_chrome_user_data_dir()
            is_standard = standard is not None and user_data_dir == standard
            reason = (
                "this Chrome build (136+) refuses remote debugging on the standard profile "
                "directory"
                if is_standard
                else "the CDP endpoint did not become ready for this profile directory"
            )
            # 浏览器已经用真实配置重启，杀掉它只会让用户更难受：保留运行并如实报错。
            raise SsstoolError(
                f"Chrome was restarted with {user_data_dir} (source: {user_data_dir_source}), "
                f"but {reason}. The browser is left running without CDP; use --profile temp "
                "for a reliable endpoint.",
                code=EXIT_CDP_UNAVAILABLE,
            ) from exc
        _abort_launch(proc, profile_dir)
        raise

    owner = _win.port_owner(port)
    pid = owner if owner else proc.pid
    name = (_win.process_name(pid) or "").lower()
    if name != "chrome.exe":
        _abort_launch(proc, profile_dir)
        raise SsstoolError(
            f"port {port} is owned by pid {pid} ({name or 'unknown'}), not chrome.exe; aborting.",
            code=EXIT_FAILURE,
        )

    session = Session(
        run_id=run_id,
        pid=pid,
        port=port,
        profile=profile,
        profile_dir=str(profile_dir) if profile_dir else None,
        project_dir=str(Path(project_dir).resolve())
        if project_dir
        else (str(Path.cwd()) if profile == "temp" else None),
        chrome=str(chrome),
        cdp_url=f"http://127.0.0.1:{port}",
        ws_url=str(version.get("webSocketDebuggerUrl") or "") or None,
        browser_version=str(version.get("Browser") or "") or None,
        started_at=datetime.now().astimezone().isoformat(timespec="seconds"),
        user_data_dir=str(user_data_dir)
        if user_data_dir
        else (str(profile_dir) if profile_dir else None),
        user_data_dir_source=user_data_dir_source if profile == "default" else "temp",
        warnings=warnings,
    )
    payload = session.to_dict()
    payload["temp_profile"] = profile == "temp"
    _state.write_session(payload)
    return session


def close_browser(*, port: int = DEFAULT_PORT, timeout: float = CLOSE_TIMEOUT) -> CloseResult:
    _win.ensure_windows()
    sessions = [
        (path, data) for path, data in _state.read_sessions() if int(data.get("port") or 0) == port
    ]
    sessions.sort(key=lambda item: str(item[1].get("started_at") or ""), reverse=True)

    if not sessions:
        owner = _win.port_owner(port)
        if owner:
            name = _win.process_name(owner) or "unknown"
            raise SsstoolError(
                f"port {port} is held by pid {owner} ({name}) but no ssstool session records it; "
                "refusing to kill an unverified process.",
                code=EXIT_FAILURE,
            )
        raise SsstoolError(f"no ssstool browser session found on port {port}.", code=EXIT_FAILURE)

    state_path, data = sessions[0]
    pid = int(data["pid"])
    warnings = [str(item) for item in (data.get("warnings") or []) if item]

    owner = _win.port_owner(port)
    if owner is not None and owner != pid:
        raise SsstoolError(
            f"port {port} is now owned by pid {owner}, not the recorded pid {pid} "
            "(pid reuse?); refusing to kill.",
            code=EXIT_FAILURE,
        )
    alive = _win.pid_alive(pid)
    if alive and (_win.process_name(pid) or "").lower() != "chrome.exe":
        raise SsstoolError(
            f"recorded pid {pid} is not chrome.exe anymore; refusing to kill.", code=EXIT_FAILURE
        )

    already_stopped = not alive
    profile_dir_raw = data.get("profile_dir")
    profile_dir = Path(str(profile_dir_raw)) if profile_dir_raw else None
    if alive:
        _win.kill_tree(pid)
        deadline = time.monotonic() + timeout
        while time.monotonic() < deadline:
            if _win.port_owner(port) != pid:
                break
            time.sleep(0.25)
        if _win.port_owner(port) == pid:
            warnings.append(f"port {port} is still held by pid {pid} after taskkill")

    profile_removed = True
    if data.get("temp_profile") and profile_dir is not None:
        if _owns_profile_dir(profile_dir):
            _kill_profile_processes(profile_dir)
            profile_removed = _remove_tree(profile_dir)
            if not profile_removed:
                warnings.append(
                    f"could not delete temp profile (files still locked): {profile_dir}"
                )
            else:
                _prune_empty_parents(profile_dir.parent)
        else:
            profile_removed = False
            warnings.append(f"refused to delete non-ssstool profile path: {profile_dir}")

    _state.delete_session(state_path)
    return CloseResult(
        port=port,
        pid=pid,
        already_stopped=already_stopped,
        profile_dir=str(profile_dir) if profile_dir else None,
        profile_removed=profile_removed,
        warnings=warnings,
    )


def profile_info() -> dict[str, object]:
    """探测真实用户配置目录，不启动也不关闭任何进程。"""
    _win.ensure_windows()
    path, source = _win.resolve_chrome_user_data_dir()
    standard = _win.standard_chrome_user_data_dir()
    return {
        "path": str(path),
        "source": source,
        "is_standard": standard is not None and path == standard,
        "exists": path.is_dir(),
    }
